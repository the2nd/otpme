# The suite tiqr has used since day one. "-S" without a length is a
# deviation from RFC 6287 that both the tiqr server library and the tiqr
# apps implement; see otpme/lib/otp/oath/ocra.py. The apps store the
# suite at enrollment and cannot be told a different one afterwards,
# which is why every token keeps its own copy.
DEFAULT_OCRA_SUITE = "OCRA-1:HOTP-SHA1-6:QH10-S"

# Custom URL schemes the stock tiqr apps register. Universal links would
# need the app to be associated with our domain, which only works for an
# app you build and publish yourself, so the schemes are what we use.
