""" tiqr token (https://tiqr.org).

Challenge-response against a shared secret using OCRA (RFC 6287). The
server shows a challenge as a QR code or a tiqrauth:// link, the phone
computes the response with the secret it holds and posts it back over
its own connection.

Unlike every other token type here the secret is generated by the
*phone* and handed to us during enrollment, so a freshly added token
carries no secret until an app has been through it. Everything that
drives that -- the enrollment and authentication flow, the endpoints the
phone talks to -- lives outside this class; this is the stored
credential and the OCRA check on it, nothing else.

What this token is worth, so nobody mistakes it for more: the response
is one-time and challenge-bound, so it beats a password and cannot be
replayed. But it is NOT phishing resistant. Nothing in the protocol ties
the response to the browser's origin -- the phone answers over its own
channel and never learns where the browser is -- so an attacker who
relays a genuine challenge onto their own page gets the user's
confirmation for their own session. Same class as TOTP and push
approval; fido2/passkey are the phishing-resistant option here. On top
of that the server has to keep the secret recoverable to verify a
response, so a database breach exposes every tiqr credential, which is
not true for passkeys.
"""
